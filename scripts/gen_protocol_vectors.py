#!/usr/bin/env python3
"""Generate docs/protocol-test-vectors.json for the BleLink protocol v1 (docs/PROTOCOL.md).

Independent reference encoder/decoder: it does not share code with the C++ implementation.
Run:  python3 scripts/gen_protocol_vectors.py [--check]
--check fails if docs/protocol-test-vectors.json is not up to date.
"""
import json
import struct
import sys
import zlib
from pathlib import Path

HELLO, MSG_START, MSG_DATA, ACK, RESUME, CANCEL, PROGRESS, MSG_RESEND = range(1, 9)
OUT = Path(__file__).resolve().parent.parent / "docs" / "protocol-test-vectors.json"


def crc32(b: bytes) -> int:
    return zlib.crc32(b) & 0xFFFFFFFF


def payload_bytes(n: int) -> bytes:
    # Deterministic test payload: byte i = (i*7 + 3) mod 256
    return bytes((i * 7 + 3) & 0xFF for i in range(n))


def hello(seq, version, max_packet, max_message, window, flags, timeout):
    return struct.pack("<BBBHIBBB", HELLO, seq, version, max_packet, max_message, window, flags, timeout)


def msg_start(seq, mid, total, crc, data):
    return struct.pack("<BBHII", MSG_START, seq, mid, total, crc) + data


def msg_data(seq, mid, data):
    return struct.pack("<BBH", MSG_DATA, seq, mid) + data


def msg_resend(seq, mid, off, data):
    return struct.pack("<BBHI", MSG_RESEND, seq, mid, off) + data


def ack(seq, mid, status):
    return struct.pack("<BBHB", ACK, seq, mid, status)


def resume(seq, mid, off):
    return struct.pack("<BBHI", RESUME, seq, mid, off)


def cancel(seq, mid, reason):
    return struct.pack("<BBHB", CANCEL, seq, mid, reason)


def progress(seq, mid, n):
    return struct.pack("<BBHI", PROGRESS, seq, mid, n)


def split(msg: bytes, mid: int, psize: int, seq0: int):
    """Split one message into packets (MSG_START + MSG_DATA...). Returns list of bytes."""
    pk = []
    seq = seq0
    first = msg[: psize - 12]
    pk.append(msg_start(seq, mid, len(msg), crc32(msg), first))
    off = len(first)
    while off < len(msg):
        seq = (seq + 1) & 0xFF
        chunk = msg[off: off + psize - 4]
        pk.append(msg_data(seq, mid, chunk))
        off += len(chunk)
    return pk


def reassemble(packets, psize):
    """Reference receiver used to self-check the vectors."""
    buf, total, crc, mid = b"", None, None, None
    exp_seq = packets[0][1]
    for p in packets:
        assert len(p) <= psize, "packet exceeds packetSize"
        assert p[1] == exp_seq, "seq"
        exp_seq = (exp_seq + 1) & 0xFF
        if p[0] == MSG_START:
            mid, total, crc = struct.unpack_from("<HII", p, 2)
            buf = p[12:]
        else:
            assert p[0] == MSG_DATA and struct.unpack_from("<H", p, 2)[0] == mid
            buf += p[4:]
    assert len(buf) == total and crc32(buf) == crc
    return buf


def h(b):
    return b.hex()


def main():
    v = {
        "description": "BleLink protocol v1 test vectors. Generated by scripts/gen_protocol_vectors.py; "
                       "all packets are hex, little-endian. See docs/PROTOCOL.md.",
        "crc32": {
            "algorithm": "CRC-32/IEEE 802.3 (zlib, reflected, poly 0xEDB88320, init 0xFFFFFFFF, xorout 0xFFFFFFFF)",
            "cases": [
                {"inputAscii": "", "crc32": "00000000"},
                {"inputAscii": "123456789", "crc32": "cbf43926"},
                {"inputAscii": "hello", "crc32": "3610a686"},
                {"inputHex": "00", "crc32": "d202ef8d"},
            ],
        },
        "payloadRule": "test payload of length N: byte[i] = (i * 7 + 3) mod 256",
    }
    for c in v["crc32"]["cases"]:
        data = c["inputAscii"].encode() if "inputAscii" in c else bytes.fromhex(c["inputHex"])
        assert "%08x" % crc32(data) == c["crc32"], c

    # --- single packets of each type ---
    small = b"hello"
    single = []

    def add(name, pkt, fields):
        single.append({"name": name, "hex": h(pkt), "length": len(pkt), "fields": fields})

    add("HELLO client (maxPacket 244, 16 MiB, window 4, flags PROGRESS, timeout 40*0.25s)",
        hello(0, 1, 244, 16 * 1024 * 1024, 4, 0x01, 40),
        {"type": 1, "seq": 0, "version": 1, "maxPacket": 244, "maxMessage": 16777216, "window": 4,
         "flags": 1, "timeout": 40})
    add("HELLO MCU (maxPacket 20, 4096 B, window 1, flags streaming, timeout 0=default)",
        hello(0, 1, 20, 4096, 1, 0x02, 0),
        {"type": 1, "seq": 0, "version": 1, "maxPacket": 20, "maxMessage": 4096, "window": 1,
         "flags": 2, "timeout": 0})
    add("MSG_START complete 5-byte message 'hello' (msgId 1)",
        msg_start(1, 1, 5, crc32(small), small),
        {"type": 2, "seq": 1, "msgId": 1, "totalLen": 5, "crc32": "%08x" % crc32(small), "payloadHex": h(small)})
    add("MSG_START empty message (msgId 2)", msg_start(2, 2, 0, 0, b""),
        {"type": 2, "seq": 2, "msgId": 2, "totalLen": 0, "crc32": "00000000", "payloadHex": ""})
    add("MSG_DATA (msgId 3, 4 bytes)", msg_data(3, 3, b"\x01\x02\x03\x04"),
        {"type": 3, "seq": 3, "msgId": 3, "payloadHex": "01020304"})
    add("ACK ok (msgId 1)", ack(1, 1, 0), {"type": 4, "seq": 1, "msgId": 1, "status": 0})
    add("ACK too large (msgId 9)", ack(2, 9, 2), {"type": 4, "seq": 2, "msgId": 9, "status": 2})
    add("RESUME (msgId 7, offset 65536)", resume(3, 7, 65536), {"type": 5, "seq": 3, "msgId": 7, "offset": 65536})
    add("CANCEL (msgId 7, reason 0)", cancel(4, 7, 0), {"type": 6, "seq": 4, "msgId": 7, "reason": 0})
    add("PROGRESS (msgId 7, 65536 bytes)", progress(5, 7, 65536),
        {"type": 7, "seq": 5, "msgId": 7, "bytesReceived": 65536})
    add("MSG_RESEND (msgId 7, offset 100, 3 bytes)", msg_resend(6, 7, 100, b"\xaa\xbb\xcc"),
        {"type": 8, "seq": 6, "msgId": 7, "offset": 100, "payloadHex": "aabbcc"})
    add("seq wrap: MSG_DATA with seq 255 followed by seq 0 is legal", msg_data(255, 3, b"\x00"),
        {"type": 3, "seq": 255, "msgId": 3, "payloadHex": "00"})
    v["packets"] = single

    # INFO characteristic value (same body as HELLO without type/seq)
    v["info"] = {
        "description": "INFO characteristic value = HELLO body (version, maxPacket, maxMessage, window, flags, timeout)",
        "hex": h(hello(0, 1, 509, 16 * 1024 * 1024, 4, 0x01, 0)[2:]),
    }

    # --- splitting at packet sizes ---
    splits = []
    for n_bytes in (1000,):
        msg = payload_bytes(n_bytes)
        for psize in (20, 182, 244, 509):
            pk = split(msg, 0x0102, psize, 1)
            assert reassemble(pk, psize) == msg
            splits.append({
                "packetSize": psize,
                "messageLength": len(msg),
                "msgId": 0x0102,
                "crc32": "%08x" % crc32(msg),
                "firstSeq": 1,
                "packetCount": len(pk),
                "startPayloadBytes": psize - 12,
                "dataPayloadBytes": psize - 4,
                "packetsHex": [h(p) for p in pk],
            })
    v["messageSplits"] = {
        "description": "A 1000-byte test message (payloadRule) split at each packetSize. Sender seq starts at 1 "
                       "(seq 0 was the HELLO). Receiver must reassemble to the same bytes and CRC.",
        "cases": splits,
    }
    # boundary cases at packetSize 20: exactly fills START; exactly fills START+1 DATA
    edge = []
    for n_bytes in (8, 9, 24, 25):
        msg = payload_bytes(n_bytes)
        pk = split(msg, 5, 20, 1)
        assert reassemble(pk, 20) == msg
        edge.append({"messageLength": n_bytes, "crc32": "%08x" % crc32(msg), "packetsHex": [h(p) for p in pk]})
    v["boundaryCases20"] = {"description": "Messages at packetSize 20 around the 8-byte START and 16-byte DATA payload "
                            "boundaries (8 = one packet, 24 = START+1 full DATA, 25 = START+DATA+1-byte DATA).",
                            "cases": edge}

    # --- interleaving ---
    big = payload_bytes(60)
    sm = b"ping"
    pb = split(big, 10, 20, 0)  # 60: START(8) + 4x DATA(16)=72>=60 -> START + 4 DATA
    ps = split(sm, 11, 20, 0)
    mix = [pb[0], pb[1], ps[0]] + pb[2:]
    seq = 1
    out = []
    for p in mix:
        out.append(bytes([p[0], seq]) + p[2:])
        seq = (seq + 1) & 0xFF
    v["interleaving"] = {
        "description": "Message 10 (60 bytes) and message 11 ('ping') interleaved at packetSize 20 "
                       "(round-robin, small message jumps in after the 2nd packet). seq 1..N. "
                       "Receiver delivers message 11 first (completion order). Then both ACKs.",
        "msg10": {"length": 60, "crc32": "%08x" % crc32(big)},
        "msg11": {"length": 4, "crc32": "%08x" % crc32(sm)},
        "packetsHex": [h(p) for p in out],
        "deliveryOrder": [11, 10],
        "ackPacketsHex": [h(ack(1, 11, 0)), h(ack(2, 10, 0))],
    }

    # --- resume ---
    r_msg = payload_bytes(60)
    r = split(r_msg, 20, 20, 1)  # seq1 START(8), seq2..5 DATA(16 each)
    # packet with seq 3 lost. Receiver saw seq1, seq2 then seq4: gap. expects offset 8+16=24 for msg 20.
    resend_off = 24
    rs = []
    seq = 7
    chunk = r_msg[resend_off: resend_off + 16 - 4]  # MSG_RESEND header 8 -> payload 12 at P=20
    chunk = r_msg[resend_off: resend_off + 12]
    rs.append(msg_resend(seq, 20, resend_off, chunk))
    off = resend_off + len(chunk)
    while off < len(r_msg):
        seq += 1
        c = r_msg[off: off + 16]
        rs.append(msg_data(seq, 20, c))
        off += len(c)
    v["resume"] = {
        "description": "Packet 3 of message 20 (60 bytes, packetSize 20) is lost. Receiver sees seq 1,2,4: gap -> "
                       "sends RESUME(20, 24) (24 = bytes it has: 8 in START + 16 in first DATA). It then drops "
                       "MSG_DATA for msg 20 (seq 4,5) until MSG_RESEND(offset 24). Sender continues with MSG_RESEND "
                       "(payload 12 bytes at packetSize 20) followed by MSG_DATA.",
        "msgLength": 60,
        "crc32": "%08x" % crc32(r_msg),
        "originalPacketsHex": [h(p) for p in r],
        "lostIndex": 2,
        "resumeHex": h(resume(1, 20, resend_off)),
        "senderResendPacketsHex": [h(p) for p in rs],
    }

    text = json.dumps(v, indent=1) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/protocol-test-vectors.json is stale; run scripts/gen_protocol_vectors.py")
            return 1
        return 0
    OUT.write_text(text)
    print("wrote", OUT, len(text), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
