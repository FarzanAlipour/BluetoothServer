#!/usr/bin/env python3
"""Turns docs/protocol-test-vectors.json into a C header for the host unit tests.

Usage: gen_vectors_h.py <protocol-test-vectors.json> <out.h>

The tests compare against the JSON itself (regenerated at build time), so a change of the vectors
is picked up without editing C code.
"""
import json
import sys


def cbytes(name, data):
    body = ", ".join("0x%02x" % b for b in data) or "0"
    return "static const uint8_t %s[] = {%s};\n" % (name, body)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, "r", encoding="utf-8") as f:
        v = json.load(f)
    out = ["/* Generated by gen_vectors_h.py from %s. Do not edit. */\n" % src.replace("\\", "/").split("/")[-1],
           "#ifndef BLELINK_TEST_VECTORS_H\n#define BLELINK_TEST_VECTORS_H\n#include <stdint.h>\n",
           "typedef struct { const uint8_t *b; uint16_t n; } vb_t;\n"]

    def bytes_list(prefix, hexes):
        names = []
        for i, h in enumerate(hexes):
            nm = "%s_%d" % (prefix, i)
            out.append(cbytes(nm, bytes.fromhex(h)))
            names.append("{%s, %d}" % (nm, len(h) // 2))
        out.append("static const vb_t %s[] = {%s};\n" % (prefix, ", ".join(names)))
        out.append("#define %s_COUNT %d\n" % (prefix.upper(), len(hexes)))

    # CRC cases
    crc = v["crc32"]["cases"]
    inputs = []
    for c in crc:
        data = c["inputAscii"].encode() if "inputAscii" in c else bytes.fromhex(c["inputHex"])
        inputs.append(data.hex())
    bytes_list("v_crc_in", inputs)
    out.append("static const uint32_t v_crc_out[] = {%s};\n" % ", ".join("0x%sU" % c["crc32"] for c in crc))

    # Single packets with decoded fields
    pk = v["packets"]
    bytes_list("v_pkt", [p["hex"] for p in pk])
    out.append("typedef struct { int type, seq, msg_id, version, max_packet, window, flags, timeout, code;\n"
               "  uint32_t value, crc, max_message; const char *payload_hex; } v_fields_t;\n")
    rows = []
    for p in pk:
        f = p["fields"]
        value = f.get("totalLen", f.get("offset", f.get("bytesReceived", 0)))
        code = f.get("status", f.get("reason", 0))
        rows.append("{%d, %d, %d, %d, %d, %d, %d, %d, %d, %uU, 0x%sU, %uU, \"%s\"}" % (
            f["type"], f["seq"], f.get("msgId", 0), f.get("version", 0), f.get("maxPacket", 0), f.get("window", 0),
            f.get("flags", 0), f.get("timeout", 0), code, value, f.get("crc32", "0"), f.get("maxMessage", 0),
            f.get("payloadHex", "")))
    out.append("static const v_fields_t v_pkt_fields[] = {\n  %s};\n" % ",\n  ".join(rows))
    out.append(cbytes("v_info", bytes.fromhex(v["info"]["hex"])))
    out.append("#define V_INFO_LEN %d\n" % (len(v["info"]["hex"]) // 2))

    # Message splits
    splits = v["messageSplits"]["cases"]
    rows = []
    for i, c in enumerate(splits):
        bytes_list("v_split%d" % i, c["packetsHex"])
        rows.append("{%d, %d, %d, 0x%sU, %d, v_split%d, %d}" % (c["packetSize"], c["messageLength"], c["msgId"],
                                                              c["crc32"], c["firstSeq"], i, len(c["packetsHex"])))
    out.append("typedef struct { int packet_size; uint32_t len; int msg_id; uint32_t crc; int first_seq;\n"
               "  const vb_t *pk; int count; } v_split_t;\n")
    out.append("static const v_split_t v_splits[] = {%s};\n#define V_SPLITS_COUNT %d\n" % (", ".join(rows), len(rows)))

    # Boundary cases at packetSize 20
    bc = v["boundaryCases20"]["cases"]
    rows = []
    for i, c in enumerate(bc):
        bytes_list("v_bound%d" % i, c["packetsHex"])
        rows.append("{%d, 0x%sU, v_bound%d, %d}" % (c["messageLength"], c["crc32"], i, len(c["packetsHex"])))
    out.append("typedef struct { uint32_t len; uint32_t crc; const vb_t *pk; int count; } v_bound_t;\n")
    out.append("static const v_bound_t v_bounds[] = {%s};\n#define V_BOUNDS_COUNT %d\n" % (", ".join(rows), len(rows)))

    # Interleaving
    il = v["interleaving"]
    bytes_list("v_il_pk", il["packetsHex"])
    bytes_list("v_il_ack", il["ackPacketsHex"])
    out.append("static const int v_il_order[] = {%s};\n" % ", ".join(str(x) for x in il["deliveryOrder"]))
    out.append("#define V_IL_LEN10 %d\n#define V_IL_CRC10 0x%sU\n#define V_IL_LEN11 %d\n#define V_IL_CRC11 0x%sU\n" % (
        il["msg10"]["length"], il["msg10"]["crc32"], il["msg11"]["length"], il["msg11"]["crc32"]))

    # Resume
    rs = v["resume"]
    bytes_list("v_rs_orig", rs["originalPacketsHex"])
    bytes_list("v_rs_resend", rs["senderResendPacketsHex"])
    out.append(cbytes("v_rs_resume", bytes.fromhex(rs["resumeHex"])))
    out.append("#define V_RS_RESUME_LEN %d\n#define V_RS_LOST %d\n#define V_RS_LEN %d\n#define V_RS_CRC 0x%sU\n" % (
        len(rs["resumeHex"]) // 2, rs["lostIndex"], rs["msgLength"], rs["crc32"]))

    out.append("#endif\n")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
